#!/bin/sh
#
# Boot the NovaOS image in QEMU.
#
# # Why this script exists when `cargo xtask run` already boots the image
#
# `cargo xtask run` is for CI: it is non-interactive, it imposes a timeout, and
# it decides pass or fail. This script is for the two things that cannot be done
# through that interface:
#
#   1. **Looking at a hang.** `cargo xtask run` kills the VM after N seconds and
#      prints the last 40 lines. That is often not enough to see where the kernel
#      stopped, and there is no way to single-step from there.
#   2. **Changing a register.** A fault handler that prints the wrong register
#      cannot be inspected after the fact.
#
# The script is POSIX `sh`. It avoids arrays, `[[ ]]`, and `pipefail`; the
# argument vector is built with `set --`, which is the portable way to carry a
# list of options through a shell script.
#
# Everything that must agree with the automated path is asserted from this
# script rather than duplicated: see the DEBUG_EXIT_IOBASE check below.
#
# # Usage
#
#   scripts/qemu.sh                 # boot the release image, QEMU GUI + serial
#   scripts/qemu.sh --headless      # no GUI; serial goes to the terminal
#   scripts/qemu.sh --keep-image    # leave nova.img on disk
#   scripts/qemu.sh --no-build      # boot whatever image is already there
#   scripts/qemu.sh --timeout 120   # headless, log to a file
#
# The default is a graphical QEMU window. The serial console is written to the
# terminal through `-serial stdio` and mirrored to a log with `tee`. With
# `--headless` or `--timeout`, the VM is started with `-display none` so it can
# run on a machine with no graphical session.

set -eu

REPO_ROOT=$(CDPATH= cd "$(dirname "$0")/.." && pwd)
TARGET_DIR=${CARGO_TARGET_DIR:-$REPO_ROOT/target}
IMG=$TARGET_DIR/novaos/nova.img
SERIAL_LOG=$TARGET_DIR/novaos/serial-interactive.log

# The two M5 test disks, generated by `cargo xtask image` beside the ISO. The
# writable one is disk 0 and the read-only one is disk 1 — the same order the
# kernel's `drivers::init` assumes, and the same order `cargo xtask run` uses.
DISK_RW=$TARGET_DIR/novaos/testdisk.raw
DISK_RO=$TARGET_DIR/novaos/testdisk-ro.raw

# ---------------------------------------------------------------------------
# Constants that must match the rest of the tree
# ---------------------------------------------------------------------------
#
# These are duplicated from `tools/xtask/src/qemu.rs` and
# `kernel/src/arch/x86_64/exit.rs`. Duplication across a shell script and two
# Rust files is normally a mistake; here it is unavoidable, so the script
# *asserts* against the Rust sources rather than trusting its own copy. A change
# to either that is not made here fails loudly at startup instead of hanging a
# VM whose tests all passed.
DEBUG_EXIT_IOBASE=0xf4
EXIT_PORT_EXPECTATION='const DEBUG_EXIT_PORT: u16 = 0xF4;'
MEMORY_MIB=2048

BUILD=true
KEEP_IMAGE=false
TIMEOUT=
HEADLESS=false

while [ $# -gt 0 ]; do
    case "$1" in
        --no-build)   BUILD=false ;;
        --keep-image) KEEP_IMAGE=true ;;
        --timeout)    TIMEOUT=$2; shift ;;
        --headless)   HEADLESS=true ;;
        -h|--help)
            sed -n '4,40p' "$0" | sed 's/^# \{0,1\}//'
            exit 0
            ;;
        *)
            echo "unknown option: $1" >&2
            exit 2
            ;;
    esac
    shift
done

# ---------------------------------------------------------------------------
# Preflight
# ---------------------------------------------------------------------------

# Fail before spending a build on a mismatch that would hang the VM.
#
# `isa-debug-exit` listens on whatever `iobase=` says — it has no fixed port. If
# this script's copy and the kernel's disagree, the kernel finishes its tests,
# writes to a port nothing is listening on, and QEMU keeps running. The symptom
# is indistinguishable from a hung kernel, which is why this is checked rather
# than documented.
if ! grep -q "$EXIT_PORT_EXPECTATION" \
        "$REPO_ROOT/kernel/src/arch/x86_64/exit.rs"; then
    cat >&2 <<EOF
error: scripts/qemu.sh writes the exit port $DEBUG_EXIT_IOBASE, but
       kernel/src/arch/x86_64/exit.rs no longer contains:

           $EXIT_PORT_EXPECTATION

QEMU would never see the kernel's exit status, and a passing test suite would
look like a hang. Update all three together:
  - kernel/src/arch/x86_64/exit.rs   (DEBUG_EXIT_PORT)
  - tools/xtask/src/qemu.rs          (DEBUG_EXIT_IOBASE)
  - scripts/qemu.sh                  (DEBUG_EXIT_IOBASE, EXIT_PORT_EXPECTATION)
EOF
    exit 1
fi

if [ "$BUILD" = true ]; then
    # `cargo xtask image` builds the kernel and packages the ESP image. Using it
    # rather than `cargo build` here means this script and the automated path
    # produce byte-identical images, so "it works interactively" implies "it works in CI".
    ( cd "$REPO_ROOT" && cargo xtask image )
fi

if [ ! -f "$IMG" ]; then
    echo "error: $IMG not found; run 'cargo xtask image' first" >&2
    exit 1
fi

if [ ! -f "$DISK_RW" ] || [ ! -f "$DISK_RO" ]; then
    echo "error: test disks not found under $TARGET_DIR/novaos/" >&2
    echo "       run 'cargo xtask image' to generate them" >&2
    exit 1
fi

# ---------------------------------------------------------------------------
# Firmware
# ---------------------------------------------------------------------------
#
# Two pflash drives, not `-bios`: OVMF's variable store has to be writable, and
# pflash is how it is made so. The second drive is a *copy* of a template —
# pointing it at the system's template directly would let one run's NVRAM writes
# corrupt every later run, including other projects on the machine.

find_ovmf() {
    kind=$1
    shift
    for dir in /usr/share/OVMF /usr/share/ovmf /usr/share/edk2/ovmf /usr/local/share/ovmf; do
        for name in "$@"; do
            if [ -f "$dir/$name" ]; then
                printf '%s\n' "$dir/$name"
                return 0
            fi
        done
    done
    echo "error: OVMF $kind image not found. Install an edk2/ovmf package." >&2
    echo "       tried: $*" >&2
    return 1
}

OVMF_CODE=$(find_ovmf code OVMF_CODE_4M.fd OVMF_CODE.fd OVMF.fd)
OVMF_VARS_TEMPLATE=$(find_ovmf variables OVMF_VARS_4M.fd OVMF_VARS.fd OVMF_VARS.ms.fd)

# A fresh variable store per run, in a directory that is ours rather than one
# shared with the system's OVMF installation.
VARS_COPY=$TARGET_DIR/novaos/OVMF_VARS-interactive.fd
mkdir -p "$(dirname "$VARS_COPY")"
cp "$OVMF_VARS_TEMPLATE" "$VARS_COPY"

# ---------------------------------------------------------------------------
# Argument vector
# ---------------------------------------------------------------------------

# `set --` is the POSIX replacement for a bash array. Every argument that
# contains a space is one word, quoted as it is added.
set -- \
    -machine q35,accel=tcg \
    -cpu qemu64 \
    -smp 1 \
    -m "${MEMORY_MIB}M" \
    -drive "if=pflash,format=raw,unit=0,readonly=on,file=$OVMF_CODE" \
    -drive "if=pflash,format=raw,unit=1,file=$VARS_COPY" \
    -drive "file=$IMG,format=raw,index=0,media=disk" \
    -drive "file=$DISK_RW,format=raw,if=none,id=nova0" \
    -device "virtio-blk-pci,drive=nova0" \
    -drive "file=$DISK_RO,format=raw,if=none,id=nova1,readonly=on" \
    -device "virtio-blk-pci,drive=nova1" \
    -netdev "user,id=novanet,guestfwd=tcp:10.0.2.100:80-cmd:/bin/cat" \
    -device "virtio-net-pci,netdev=novanet" \
    -device "isa-debug-exit,iobase=$DEBUG_EXIT_IOBASE,iosize=0x04" \
    -no-reboot

echo "image:    $IMG"
echo "firmware: $OVMF_CODE"
echo "vars:     $VARS_COPY  (a copy; the system template is never written)"
echo

# ---------------------------------------------------------------------------
# Launch
# ---------------------------------------------------------------------------

# POSIX timeout: a background watcher kills the child after `seconds`.
# `timeout` is a GNU utility, not part of POSIX, so this script does not depend
# on it. A killed QEMU can still exit 0 on SIGTERM, so the watcher records that
# it fired in a marker file; the caller decides "hang" from that marker, not
# from the child's exit status alone.
run_with_timeout() {
    seconds=$1
    shift
    marker=$TARGET_DIR/novaos/qemu-timeout.$$
    rm -f "$marker"

    "$@" &
    child=$!
    (
        sleep "$seconds"
        kill -TERM "$child" 2>/dev/null || true
        : > "$marker"
    ) &
    watcher=$!

    child_status=0
    wait "$child" || child_status=$?

    kill -TERM "$watcher" 2>/dev/null || true
    wait "$watcher" 2>/dev/null || true

    if [ -e "$marker" ]; then
        rm -f "$marker"
        return 124
    fi
    rm -f "$marker"
    return "$child_status"
}

exit_status=0

if [ -n "$TIMEOUT" ]; then
    # A timeout means nobody is there to type, so the file log is more useful
    # than an interactive prompt that the timeout will kill anyway.
    echo "serial:   $SERIAL_LOG (timeout ${TIMEOUT}s)"
    if run_with_timeout "$TIMEOUT" qemu-system-x86_64 "$@" \
        -display none -serial "file:$SERIAL_LOG"; then
        status=0
    else
        status=$?
    fi
    echo
    if [ "$status" -eq 124 ]; then
        echo "timed out after ${TIMEOUT}s. This is a hang, not a test failure:"
        echo "the kernel most likely never reached isa-debug-exit."
    else
        # QEMU's `isa-debug-exit` reports odd statuses for failures; a completed
        # passing suite exits 0 on this QEMU build.
        echo "QEMU exited with $status; the log is in $SERIAL_LOG"
    fi
    exit_status=$status

    # --- The `[NOVA-TEST]` verdict -------------------------------------
    #
    # The plan requires the serial log to be parsed for the `[NOVA-TEST]`
    # lines, and requires the counts to be checked rather than a summary
    # *word*: a kernel that prints "all suites passed" and then reports
    # `failed=5` has contradicted itself, and the counts are the checkable
    # half.
    echo
    if [ ! -f "$SERIAL_LOG" ]; then
        echo "[NOVA-TEST] no serial log at $SERIAL_LOG"
    else
        local_result=$(grep -E '\[NOVA-TEST\] (RESULT|SUMMARY)' "$SERIAL_LOG" || true)
        if [ -z "$local_result" ]; then
            echo "[NOVA-TEST] the kernel never printed a summary."
            echo "            It most likely never reached the test harness."
        else
            echo "$local_result"
        fi

        # The count of failures, if the kernel reported one.
        failed=$(sed -n 's/.*\[NOVA-TEST\] RESULT .*failed=\([0-9][0-9]*\)$/\1/p' \
            "$SERIAL_LOG" | tail -1)
        if [ -n "$failed" ] && [ "$failed" != "0" ]; then
            echo "[NOVA-TEST] FAILED: ${failed} case(s) failed."
            grep -E '\[NOVA-TEST\].*FAIL|\[NOVA\] ERR' "$SERIAL_LOG" | head -20
        elif [ -n "$failed" ]; then
            echo "[NOVA-TEST] PASSED: no failures reported."
        fi
    fi
elif [ "$HEADLESS" = true ]; then
    echo "serial:   $SERIAL_LOG (headless)"
    if qemu-system-x86_64 "$@" -display none -serial "file:$SERIAL_LOG"; then
        exit_status=0
    else
        exit_status=$?
    fi
else
    # The GUI is the default, as requested. `-serial stdio` keeps the kernel's
    # serial console visible in the terminal while QEMU draws the framebuffer
    # in its window; `tee` preserves the log for later inspection.
    echo "serial:   stdio and $SERIAL_LOG"
    echo
    qemu-system-x86_64 "$@" -display gtk -serial stdio | tee "$SERIAL_LOG"
    exit_status=0
fi

if [ "$KEEP_IMAGE" = false ] && [ "$BUILD" = true ]; then
    # Only remove what this script built. If the caller passed --no-build, the image
    # was theirs and deleting it would be destroying something they asked to keep.
    rm -f "$IMG"
fi

exit "$exit_status"
